function tbl(s,values,widths,{x=44,y=126,h=44}={}){
  const t=s.tables.add({rows:values.length,columns:widths.length,left:x,top:y,width:widths.reduce((a,b)=>a+b,0),height:h*values.length,columnWidths:widths,values});
  t.styleOptions={headerRow:false,bandedRows:false,firstColumn:false,lastColumn:false};
  t.borders.assign({style:'solid',fill:'#DCD4E7',width:0.75});
  for(let i=0;i<values.length;i++){
    t.rows[i].height=h;
    for(let j=0;j<widths.length;j++){
      const c=t.getCell(i,j);
      c.fill=i===0?purple:i%2===0?subtle:'#FFFFFF';
      c.text.style={typeface:font,fontSize:(i===0?19:18)*4/3,color:i===0?'#FFFFFF':ink,bold:i===0,verticalAlignment:'middle'};
    }
  }
  return t;
}

